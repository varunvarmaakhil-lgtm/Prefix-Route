def load_cells(raw):
    rows = []
    for p in glob.glob(os.path.join(raw, "*.json")):
        if not os.path.exists(p + ".done"):
            continue
        r = json.load(open(p))
        row = dict(r["cell"])
        row.update({k: v for k, v in r["metrics"].items() if not isinstance(v, (list, tuple))})
        row.update({"cap_blocks": r["cap_blocks"], "ws_blocks": r["ws_blocks"], "cost_source": r["cost_source"],
                    "wall_s": r["wall_s"]})
        rows.append(row)
    df = pd.DataFrame(rows)
    if "tool_median_s" not in df:
        df["tool_median_s"] = np.nan
    if "headroom" not in df:
        df["headroom"] = 2.0
    for k, v in {"think_scale": 1.0, "growth_scale": 1.0, "turns_scale": 1.0, "caching": True}.items():
        if k not in df:
            df[k] = v
        df[k] = df[k].fillna(v).infer_objects()
    return df


def agg(df, keys, metric):
    g = df.groupby(keys)[metric]
    out = g.agg(["mean", "std", "count"]).reset_index()
    out["ci"] = [T95.get(int(n) - 1, 1.96) * s / np.sqrt(n) if n > 1 else np.nan
                 for s, n in zip(out["std"], out["count"])]
    return out


class Macros:
    def __init__(self):
        self.d = {}

    def add(self, name, value, fmt="{:.2f}"):
        name = "".join(ch for ch in name if ch.isalnum())
        if value is None or (isinstance(value, float) and not np.isfinite(value)):
            return
        self.d[name] = fmt.format(value) if not isinstance(value, str) else value

    def write(self, path):
        with open(path, "w") as fh:
            fh.write("% generated by analysis/make_tables.py -- do not edit\n")
            for k, v in sorted(self.d.items()):
                fh.write(f"\\expandafter\\def\\csname pr@{k}\\endcsname{{{v}}}\n")


def ms(x):
    return 1000.0 * x


def sim_section(df, M, tables, figs):
    df = df[df.tool_median_s.isna()]          # tool-latency sweep cells are analysed by analysis/latency.py
    base = (df.caching == True) & (df.think_scale == 1.0) & (df.growth_scale == 1.0) & (df.turns_scale == 1.0)  # noqa: E712
    main = df[base & (df.N == 4) & (df.cap_frac == 1.0) & (df.util == 0.7)]
    M.add("nCells", len(df), "{:d}")
    M.add("nSeeds", int(main.seed.nunique()) if len(main) else None, "{:d}")
    M.add("costSource", str(df.cost_source.iloc[0]).replace("_", "-") if len(df) else None)
    summary = {}
    # ---- main table
    if len(main):
        rows = []
        for wl in ["chat", "agentic", "synth"]:
            d = main[main.workload == wl]
            if d.empty:
                continue
            ref = d[d.policy == "oracle"].ttft_p95.mean()
            for p in POL:
                x = d[d.policy == p]
                if x.empty:
                    continue
                a = agg(x, ["policy"], "ttft_p95").iloc[0]
                row = {"workload": wl, "policy": p, "p95_ms": ms(a["mean"]), "p95_ci_ms": ms(a["ci"]),
                       "p50_ms": ms(x.ttft_p50.mean()), "hit": x.hit_rate.mean(), "cv": x.imbalance_cv_work.mean(),
                       "slo": x.slo_viol.mean(), "thpt": x.thpt_req_s.mean(), "vs_oracle": a["mean"] / ref,
                       "n": int(a["count"])}
                rows.append(row)
                key = f"{wl}{p}"
                M.add(key + "pninetyfive", row["p95_ms"], "{:.0f}")
                M.add(key + "pninetyfiveci", row["p95_ci_ms"], "{:.0f}")
                M.add(key + "hit", 100 * row["hit"], "{:.1f}")
                M.add(key + "cv", row["cv"], "{:.3f}")
                M.add(key + "slo", 100 * row["slo"], "{:.1f}")
                M.add(key + "vsoracle", row["vs_oracle"], "{:.2f}")
        t = pd.DataFrame(rows)
        t.to_csv(os.path.join(tables, "main.csv"), index=False)
        summary["main"] = t.to_dict("records")
        write_main_tex(t, os.path.join(figs, "..", "tables_main.tex"))
        # ---- headline: chat vs agentic delta per policy (p95 relative to the clairvoyant reference)
        piv = t.pivot(index="policy", columns="workload", values="vs_oracle")
        deltas = {}
        for p in piv.index:
            if "chat" in piv and "agentic" in piv:
                deltas[p] = float(piv.loc[p, "agentic"] - piv.loc[p, "chat"])
                M.add(f"delta{p}", deltas[p], "{:+.2f}")
        summary["delta_vs_oracle_agentic_minus_chat"] = deltas
        # cache-aware benefit over least-loaded, per workload (p95 reduction %)
        for wl in ["chat", "agentic", "synth"]:
            d = t[t.workload == wl].set_index("policy")
            if {"cache_aware", "least_loaded"} <= set(d.index):
                red = 100 * (1 - d.loc["cache_aware", "p95_ms"] / d.loc["least_loaded", "p95_ms"])
                M.add(f"{wl}cabenefit", red, "{:.0f}")
                summary[f"{wl}_cache_aware_vs_least_loaded_p95_reduction_pct"] = float(red)
            if {"session_affinity", "least_loaded"} <= set(d.index):
                red = 100 * (1 - d.loc["session_affinity", "p95_ms"] / d.loc["least_loaded", "p95_ms"])
                M.add(f"{wl}sabenefit", red, "{:.0f}")
        # rank agreement chat vs agentic (Kendall tau over policies by p95)
        if {"chat", "agentic"} <= set(t.workload):
            from scipy.stats import kendalltau
            a = t[t.workload == "chat"].set_index("policy").p95_ms
            b = t[t.workload == "agentic"].set_index("policy").p95_ms
            common = a.index.intersection(b.index)
            tau = kendalltau(a[common], b[common]).statistic
            M.add("tauChatAgentic", tau, "{:.2f}")
            summary["kendall_tau_chat_vs_agentic"] = float(tau)
            summary["rank_chat"] = list(a[common].sort_values().index)
            summary["rank_agentic"] = list(b[common].sort_values().index)
        fig_policy_bars(t, os.path.join(figs, "fig_policy_p95.pdf"))
        fig_tradeoff(main, os.path.join(figs, "fig_tradeoff.pdf"))
    # ---- capacity sweep (RQ3)
    if "headroom" not in df:
        df["headroom"] = 2.0
    hr1 = df[(df.headroom == 1.0) & (df.N == 4)]
    if len(hr1):
        a = agg(hr1, ["workload", "cap_frac", "policy"], "ttft_p95")
        a.to_csv(os.path.join(tables, "capacity_headroom1.csv"), index=False)
        for (wl, cf, p), g in a.groupby(["workload", "cap_frac", "policy"]):
            M.add(f"hrone{wl}{str(cf).replace('.', 'p')}{p}", ms(g["mean"].iloc[0]), "{:.0f}")
    cap = df[(df.caching == True) & (df.N == 4) & (df.util == 0.7) & (df.growth_scale == 1.0) & (df.turns_scale == 1.0) & (df.headroom == 2.0)]  # noqa: E712
    if cap.cap_frac.nunique() > 1:
        c = agg(cap, ["workload", "think_scale", "cap_frac", "policy"], "ttft_p95")
        h = agg(cap, ["workload", "think_scale", "cap_frac", "policy"], "hit_rate")
        c["hit"] = h["mean"].values
        c.to_csv(os.path.join(tables, "capacity.csv"), index=False)
        summary["capacity"] = {}
        for (wl, ts), g in c.groupby(["workload", "think_scale"]):
            ranks = {}
            for cf, gg in g.groupby("cap_frac"):
                ranks[float(cf)] = list(gg.sort_values("mean").policy)
            summary["capacity"][f"{wl}|think{ts:g}"] = ranks
            tag = f"{wl}think{int(ts)}"
            for p in POL:
                lo = g[(g.policy == p) & (g.cap_frac == g.cap_frac.min())]["mean"]
                hi = g[(g.policy == p) & (g.cap_frac == g.cap_frac.max())]["mean"]
                if len(lo) and len(hi):
                    M.add(f"cap{tag}{p}lo", ms(lo.iloc[0]), "{:.0f}")
                    M.add(f"cap{tag}{p}hi", ms(hi.iloc[0]), "{:.0f}")
                    M.add(f"cap{tag}{p}ratio", lo.iloc[0] / hi.iloc[0], "{:.1f}")
            for cf in sorted(g.cap_frac.unique()):
                for p in POL:
                    x = g[(g.policy == p) & (g.cap_frac == cf)]
                    if len(x):
                        M.add(f"cap{tag}{str(cf).replace('.', 'p')}{p}", ms(x["mean"].iloc[0]), "{:.0f}")
                        M.add(f"cap{tag}{str(cf).replace('.', 'p')}{p}hit", 100 * x["hit"].iloc[0], "{:.1f}")
            best_lo = ranks.get(float(g.cap_frac.min()), [None])[0]
            best_hi = ranks.get(float(g.cap_frac.max()), [None])[0]
            if best_lo:
                M.add(f"cap{tag}bestlo", POL_LABEL[best_lo])
                M.add(f"cap{tag}besthi", POL_LABEL[best_hi])
        fig_capacity(c, os.path.join(figs, "fig_capacity.pdf"))
    # ---- replica count, utilisation, synthetic sweeps: CSV only (+ a few macros)
    for grp, key in [("N", "nrep"), ("util", "util")]:
        d = df[(df.headroom == 2.0) & (df.caching == True) & (df.cap_frac == 1.0) & (df.think_scale == 1.0) & (df.growth_scale == 1.0) & (df.turns_scale == 1.0)]  # noqa: E712
        d = d[(d.N == 4) | (grp == "N")] if grp == "util" else d[d.util == 0.7]
        if d[grp].nunique() > 1:
            a = agg(d, ["workload", grp, "policy"], "ttft_p95")
            a.to_csv(os.path.join(tables, f"{key}.csv"), index=False)
            for (wl, v), g in a.groupby(["workload", grp]):
                M.add(f"{key}{wl}{str(v).replace('.', 'p')}best", POL_LABEL[g.sort_values('mean').policy.iloc[0]])
                for _, row in g.iterrows():
                    M.add(f"{key}{wl}{str(v).replace('.', 'p')}{row.policy}", ms(row['mean']), "{:.0f}")
    syn = df[(df.workload == "synth") & (df.headroom == 2.0) & (df.caching == True) & (df.N == 4) & (df.cap_frac == 1.0) & (df.util == 0.7)]  # noqa: E712
    for dim in ["think_scale", "growth_scale", "turns_scale"]:
        others = [x for x in ["think_scale", "growth_scale", "turns_scale"] if x != dim]
        d = syn[(syn[others[0]] == 1.0) & (syn[others[1]] == 1.0)]
        if d[dim].nunique() > 1:
            a = agg(d, [dim, "policy"], "ttft_p95")
            hr = agg(d, [dim, "policy"], "hit_rate")
            a["hit"] = hr["mean"].values
            a.to_csv(os.path.join(tables, f"synth_{dim}.csv"), index=False)
            for v, g in a.groupby(dim):
                for _, row in g.iterrows():
                    M.add(f"syn{dim.split('_')[0]}{str(v).replace('.', 'p')}{row.policy}", ms(row['mean']), "{:.0f}")
                M.add(f"syn{dim.split('_')[0]}{str(v).replace('.', 'p')}best", POL_LABEL[g.sort_values('mean').policy.iloc[0]])
    nc = df[df.caching == False]  # noqa: E712
    if len(nc) and len(main):
        for wl in ["chat", "agentic", "synth"]:
            off = nc[(nc.workload == wl) & (nc.policy == "least_loaded")].ttft_p95.mean()
            on = main[(main.workload == wl) & (main.policy == "least_loaded")].ttft_p95.mean()
            if np.isfinite(off) and np.isfinite(on):
                M.add(f"{wl}nocachepninetyfive", ms(off), "{:.0f}")
                M.add(f"{wl}cachinggain", off / on, "{:.1f}")
    return summary


def measure_section(mdir, M, tables, figs):
    summary = {}
    cp = os.path.join(mdir, "curves.parquet")
    if os.path.exists(cp):
        s = pd.read_parquet(cp)
        s.to_csv(os.path.join(tables, "curves.csv"), index=False)
        on = s[(s.tag == "on") & (s.c == 1)]
        off = s[(s.tag == "nocache") & (s.c == 1)]
        for L in sorted(s.L.unique()):
            for h in (0.0, 0.5, 0.9, 1.0):
                x = on[(on.L == L) & (on.h == h)].ttft_p50
                if len(x):
                    M.add(f"measL{L}h{int(h * 100)}", ms(x.iloc[0]), "{:.0f}")
            x0, x1 = on[(on.L == L) & (on.h == 0.0)].ttft_p50, on[(on.L == L) & (on.h == 0.9)].ttft_p50
            if len(x0) and len(x1):
                M.add(f"measL{L}speedupninety", x0.iloc[0] / x1.iloc[0], "{:.1f}")
            y0 = off[(off.L == L) & (off.h == 0.0)].ttft_p50
            if len(y0) and len(x0):
                M.add(f"measL{L}overhead", 100 * (x0.iloc[0] / y0.iloc[0] - 1), "{:+.0f}")
        pr = s[s.tag == "pressure"]
        onl = s[s.tag == "on"]
        for c in sorted(pr.c.unique()):
            for h in (0.0, 0.25, 0.5, 0.9):
                g = pr[(pr.c == c) & (pr.h == h)]
                o = onl[(onl.c == c) & (onl.h == h) & (onl.L == 4096)]
                if not len(g):
                    continue
                tag = f"presc{c}h{int(h * 100)}"
                if "ctr_hit" in g and np.isfinite(g.ctr_hit.iloc[0]):
                    M.add(tag + "ctrhit", 100 * g.ctr_hit.iloc[0], "{:.0f}")
                if "preemptions" in g:
                    M.add(tag + "preempt", g.preemptions.iloc[0], "{:.0f}")
                    M.add(tag + "qinfl", g.query_inflation.iloc[0], "{:.1f}")
                M.add(tag + "kvmax", 100 * g.kv_usage_max.iloc[0], "{:.0f}")
                if len(o):
                    M.add(tag + "ttftratio", g.ttft_p50.iloc[0] / o.ttft_p50.iloc[0], "{:.1f}")
                    M.add(tag + "ttft", ms(g.ttft_p50.iloc[0]), "{:.0f}")
        for L in sorted(onl.L.unique()):
            g = onl[(onl.c == 1) & (onl.L == L) & (onl.h == 0.75)]
            if len(g) and "ctr_hit" in g and np.isfinite(g.ctr_hit.iloc[0]):
                M.add(f"measL{L}ctrhitseventyfive", 100 * g.ctr_hit.iloc[0], "{:.1f}")
        for L in (4096, 16384):
            for c in (16, 32):
                g0 = onl[(onl.c == c) & (onl.L == L) & (onl.h == 0.0)]
                g9 = onl[(onl.c == c) & (onl.L == L) & (onl.h == 0.9)]
                if len(g0) and len(g9):
                    M.add(f"measL{L}c{c}h0", ms(g0.ttft_p50.iloc[0]), "{:.0f}")
                    M.add(f"measL{L}c{c}h90", ms(g9.ttft_p50.iloc[0]), "{:.0f}")
        M.add("measSettings", len(s), "{:d}")
        fig_measure(s, os.path.join(figs, "fig_measure.pdf"))
    for name, path in [("cost", "costmodel.json"), ("emp", "fit_empirical.json"), ("corr", "correctness.json")]:
        p = os.path.join(mdir, path)
        if os.path.exists(p):
            summary[name] = json.load(open(p))
    if "cost" in summary:
        f = summary["cost"].get("fit", {})
        M.add("fitRtwo", f.get("r2"), "{:.3f}")
        M.add("fitMapeTTFT", 100 * f["mape_ttft"] if f.get("mape_ttft") is not None else None, "{:.1f}")
        M.add("fitMapeITL", 100 * f["mape_itl"] if f.get("mape_itl") is not None else None, "{:.1f}")
        c = summary["cost"]
        M.add("costa", 1000 * c["a"], "{:.2f}")
        M.add("costb", 1e6 * c["b"], "{:.1f}")
        M.add("costc", 1e6 * c["c"], "{:.1f}")
        M.add("costdp", 1e6 * c["dp"], "{:.2f}")
        M.add("costdd", 1e6 * c["dd"], "{:.1f}")
        caps = c.get("kv_capacity_tokens", {})
        if "server_on.log" in caps:
            M.add("kvcaptokens", caps["server_on.log"], "{:,}")
    if summary.get("emp"):
        M.add("empRtwoLog", summary["emp"]["r2_log"], "{:.3f}")
        M.add("empRtwoLin", summary["emp"]["r2_linear"], "{:.3f}")
        M.add("empMape", 100 * summary["emp"]["mape"], "{:.1f}")
        summary["emp"].pop("residuals", None)
    if "corr" in summary:
        ag = summary["corr"].get("agentic", {})
        for k, v in ag.items():
            if v:
                M.add("corr" + k.replace("-vs-", "vs"), 100 * v["exact_match"], "{:.1f}")
                M.add("corrdeg" + k.replace("-vs-", "vs"), 100 * v["degenerate_a"], "{:.1f}")
        y0 = ag.get("nocache0-vs-nocache1")
        if y0:
            M.add("corroneinn", 1.0 / max(1e-9, 1 - y0["exact_match"]), "{:.0f}")
        x = ag.get("on0-vs-nocache0")
        if x and x.get("first_div_median") is not None:
            M.add("corrfirstdiv", x["first_div_median"], "{:.0f}")
        pb = summary["corr"].get("probe", {})
        y = pb.get("on:cold-vs-warm")
        if y:
            M.add("probeoncoldvswarmdiff", round((1 - y["exact_match"]) * y["n"]), "{:d}")
        for k, v in pb.items():
            if v:
                M.add("probe" + k.replace("-vs-", "vs").replace(":", ""), 100 * v["exact_match"], "{:.0f}")
    for suffix, tag in (("", "base"), ("_cachedcost", "cc")):
        sp = os.path.join(os.path.dirname(tables.rstrip("/\\")), "tables", f"sim_bias_summary{suffix}.json")
        sp = sp if os.path.exists(sp) else os.path.join(tables, f"sim_bias_summary{suffix}.json")
        if os.path.exists(sp):
            b = json.load(open(sp))
            M.add(f"bias{tag}n", b["n_settings"], "{:d}")
            M.add(f"bias{tag}med", b["resid_pct_median_on"], "{:+.1f}")
            M.add(f"bias{tag}hzero", b["resid_pct_by_h"]["0.0"], "{:+.1f}")
            M.add(f"bias{tag}hninety", b["resid_pct_by_h"]["0.9"], "{:+.1f}")
            M.add(f"bias{tag}hone", b["resid_pct_by_h"]["1.0"], "{:+.0f}")
            M.add(f"bias{tag}cone", b["resid_pct_by_c"]["1"], "{:+.1f}")
            M.add(f"bias{tag}cthirtytwo", b["resid_pct_by_c"]["32"], "{:+.1f}")
            M.add(f"bias{tag}pen", 100 * (b["penalty_ratio_median"] - 1), "{:+.0f}")
            M.add(f"bias{tag}penone", 100 * (b["penalty_ratio_c1"] - 1), "{:+.0f}")
            M.add(f"bias{tag}rho", b["spearman_all"], "{:.2f}")
    vc = os.path.join(mdir, "validation_cachedcost.json")
    if os.path.exists(vc):
        v = json.load(open(vc))
        M.add("valccpfifty", v["ttft_p50_err_pct"], "{:+.0f}")
        M.add("valccpninetyfive", v["ttft_p95_err_pct"], "{:+.0f}")
        M.add("valccspearman", v["ttft_spearman"], "{:.2f}")
    cc = os.path.join(mdir, "costmodel_cachedcost.json")
    if os.path.exists(cc):
        M.add("coste", 1e6 * json.load(open(cc))["e"], "{:.2f}")
    vp = os.path.join(mdir, "validation.json")
    if os.path.exists(vp):
        v = json.load(open(vp))
        summary["validation"] = v
        M.add("valspearman", v.get("ttft_spearman"), "{:.2f}")
        for k in ("ttft_p50_err_pct", "ttft_p95_err_pct", "hit_err_pp"):
            if v.get(k) is not None:
                M.add("val" + k.replace("_", ""), v[k], "{:+.0f}" if "pct" in k else "{:+.1f}")
    return summary


# ------------------------------------------------------------------ figures
def _style():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 7, "axes.labelsize": 7, "legend.fontsize": 6, "xtick.labelsize": 6,
                         "ytick.labelsize": 6, "axes.spines.top": False, "axes.spines.right": False,
                         "axes.grid": True, "grid.color": "#e4e3dc", "grid.linewidth": 0.5, "axes.edgecolor": "#8a897f",
                         "lines.linewidth": 1.2, "pdf.fonttype": 42, "font.family": "serif"})
    return plt


def fig_measure(s, path):
    plt = _style()
    on = s[(s.tag == "on") & (s.c == 1)]
    off = s[(s.tag == "nocache") & (s.c == 1)]
    fig, ax = plt.subplots(1, 2, figsize=(3.5, 1.7))
    for i, L in enumerate(sorted(on.L.unique())):
        g = on[on.L == L].sort_values("h")
        ax[0].plot(g.h, ms(g.ttft_p50), marker=MARKERS[i], ms=3, color=COLORS[i], label=f"{L // 1024}k")
        g2 = off[off.L == L].sort_values("h")
        if len(g2):
            ax[0].plot(g2.h, ms(g2.ttft_p50), ls="--", lw=0.8, color=COLORS[i])
    ax[0].set_yscale("log")
    ax[0].set_xlabel("prefix hit fraction")
