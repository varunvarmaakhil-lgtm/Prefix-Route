def write_main_tex(t, path):
    wls = [w for w in ["chat", "agentic", "synth"] if w in set(t.workload)]
    lines = ["\\begin{tabular}{l" + "rr" * len(wls) + "}", "\\toprule",
             " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{WL_LABEL[w]}}}" for w in wls) + " \\\\",
             " ".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(wls))),
             "Policy & " + " & ".join("p95 (ms) & hit \\%" for _ in wls) + " \\\\", "\\midrule"]
    for p in POL:
        cells = []
        for w in wls:
            r = t[(t.workload == w) & (t.policy == p)]
            if len(r):
                r = r.iloc[0]
                cells += [f"{r.p95_ms:.0f}$\\pm${r.p95_ci_ms:.0f}", f"{100 * r.hit:.1f}"]
            else:
                cells += ["--", "--"]
        lines.append(POL_LABEL[p] + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(path, "w").write("\n".join(lines) + "\n")


